export function suggestBodyType(gender, weight) {
  const numericWeight = Number(weight)
  if (!gender || !numericWeight) return ''

  if (gender === 'M') {
    if (numericWeight >= 50 && numericWeight <= 70) return '1'
    if (numericWeight >= 71 && numericWeight <= 80) return '3'
    if (numericWeight >= 81 && numericWeight <= 200) return '5'
    if (numericWeight >= 55 && numericWeight <= 70) return '4'
    return ''
  }

  if (numericWeight >= 40 && numericWeight <= 50) return '1'
  if (numericWeight >= 61 && numericWeight <= 70) return '3'
  if (numericWeight >= 71 && numericWeight <= 200) return '5'
  if (numericWeight >= 51 && numericWeight <= 60) return '4'
  return ''
}

export function getChildrenLivingOptions(childCount) {
  if (!childCount || childCount === '0') return []
  const words = ['One', 'Two', 'Three', 'Four']
  const count = Number(childCount)
  const options = [{ value: '0', label: 'No Children' }]
  for (let i = 1; i <= count; i += 1) {
    options.push({ value: String(i), label: words[i - 1] })
  }
  return options
}

export function maskMobileNumber(mobile = '9876543210') {
  if (mobile.length < 10) return mobile
  return `${mobile.slice(0, 2)}XXXXXX${mobile.slice(8, 10)}`
}
